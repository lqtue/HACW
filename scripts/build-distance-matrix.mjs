#!/usr/bin/env node
// Bake a walking-distance matrix between the (fixed) destinations, so the planner
// costs/optimises routes on real street distances instead of straight-line ×1.3.
//
//   node scripts/build-distance-matrix.mjs            # fallback: haversine × DETOUR
//   ORS_TOKEN=xxx node scripts/build-distance-matrix.mjs --ors   # real foot-walking
//
// Output: src/lib/data/distances.js — { source, ids[N], m[N][N] } (metres, ints).
// Indexed by destinations.json order. route.js looks it up by dest id, falling back
// to haversine×DETOUR for any point not in the matrix (e.g. a live GPS fix).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { distanceMeters } from '../src/lib/geo.js';
import { DETOUR } from '../src/lib/route.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dest = JSON.parse(fs.readFileSync(path.join(root, 'src/lib/data/destinations.json'), 'utf8'));
const ids = dest.map((d) => d.id);
const pts = dest.map((d) => ({ lat: d.lat, lng: d.lng }));
const N = ids.length;

function fallback() {
  return pts.map((a) => pts.map((b) => Math.round(distanceMeters(a, b) * DETOUR)));
}

async function ors() {
  const token = process.env.ORS_TOKEN;
  if (!token) throw new Error('ORS_TOKEN env required for --ors');
  const res = await fetch('https://api.openrouteservice.org/v2/matrix/foot-walking', {
    method: 'POST',
    headers: { Authorization: token, 'Content-Type': 'application/json' },
    body: JSON.stringify({ locations: pts.map((p) => [p.lng, p.lat]), metrics: ['distance'] })
  });
  if (!res.ok) throw new Error(`ORS ${res.status}: ${await res.text()}`);
  const { distances } = await res.json();
  if (!Array.isArray(distances) || distances.length !== N) throw new Error('bad ORS matrix shape');
  // ORS returns metres (floats), null for unroutable — patch nulls with the fallback
  return distances.map((row, i) =>
    row.map((v, j) => (v == null ? Math.round(distanceMeters(pts[i], pts[j]) * DETOUR) : Math.round(v)))
  );
}

// Actual walking-leg geometry (the polyline to DRAW), so the map shows real streets
// instead of a straight dash through the shophouses. The Matrix endpoint returns only
// distances, so geometry needs one Directions call per pair — 300 unordered pairs, one
// leg reused reversed for the other direction. Throttled under the free-tier rate.
// Keyed "i_j" with i<j by destinations.json index; coords [lng,lat] rounded to 5 dp.
const legKey = (i, j) => (i < j ? `${i}_${j}` : `${j}_${i}`);
const rnd = (v) => Math.round(v * 1e5) / 1e5;

async function orsLegs() {
  const token = process.env.ORS_TOKEN;
  if (!token) throw new Error('ORS_TOKEN env required for --geom');
  const paths = {};
  const pairs = [];
  for (let i = 0; i < N; i++) for (let j = i + 1; j < N; j++) pairs.push([i, j]);
  let done = 0;
  for (const [i, j] of pairs) {
    const res = await fetch('https://api.openrouteservice.org/v2/directions/foot-walking/geojson', {
      method: 'POST',
      headers: { Authorization: token, 'Content-Type': 'application/json' },
      body: JSON.stringify({ coordinates: [[pts[i].lng, pts[i].lat], [pts[j].lng, pts[j].lat]] })
    });
    if (res.status === 429) {
      // rate-limited — wait out the minute window and retry the same pair
      await new Promise((r) => setTimeout(r, 60000));
      pairs.push([i, j]);
      continue;
    }
    if (!res.ok) throw new Error(`ORS directions ${i}-${j} ${res.status}: ${await res.text()}`);
    const gj = await res.json();
    const coords = gj?.features?.[0]?.geometry?.coordinates;
    // unroutable pair -> leave it out; route.js draws a straight leg for a missing key
    if (Array.isArray(coords) && coords.length > 1) paths[legKey(i, j)] = coords.map(([x, y]) => [rnd(x), rnd(y)]);
    if (++done % 25 === 0) console.log(`  legs ${done}/${pairs.length}…`);
    await new Promise((r) => setTimeout(r, 1600)); // ~37/min, under the 40/min free tier
  }
  return paths;
}

const useOrs = process.argv.includes('--ors');
const useGeom = process.argv.includes('--geom');

const m = useOrs ? await ors() : fallback();
const source = useOrs ? 'ors:foot-walking' : 'fallback:haversine*detour';

const distOut = `// GENERATED by scripts/build-distance-matrix.mjs — do not edit by hand.
// Walking-distance matrix (metres) between destinations, indexed by destinations.json order.
// source: ${source}
export default ${JSON.stringify({ source, ids, m })};
`;
fs.writeFileSync(path.join(root, 'src/lib/data/distances.js'), distOut);
console.log(`distances.js written — ${N}×${N}, source=${source}, ${(Buffer.byteLength(distOut) / 1024).toFixed(1)} KB`);

// Geometry is optional: only baked with --geom (300 slow calls). Without it, write a
// straight-line fallback so route.js/RouteMap import cleanly and just draw dashes.
const legPaths = useGeom ? await orsLegs() : {};
const legSource = useGeom ? 'ors:foot-walking' : 'fallback:straight';
const legOut = `// GENERATED by scripts/build-distance-matrix.mjs --geom — do not edit by hand.
// Walking-leg polylines to DRAW on the map. Keyed "i_j" (i<j) by destinations.json
// index; coords [lng,lat]. A missing pair -> route.js draws a straight leg.
// source: ${legSource}
export default ${JSON.stringify({ source: legSource, ids, paths: legPaths })};
`;
fs.writeFileSync(path.join(root, 'src/lib/data/legs.js'), legOut);
console.log(`legs.js written — ${Object.keys(legPaths).length} legs, source=${legSource}, ${(Buffer.byteLength(legOut) / 1024).toFixed(1)} KB`);
