// Every word in the app, laid out to read and hand to a translator.
//
//   node scripts/export-full-text.mjs      ->  content/full-text.md     (Vietnamese, the source)
//   node scripts/export-full-text.mjs en   ->  content/full-text-en.md  (English, what ships today)
//
// Vietnamese is the source the other languages are translated FROM; the English
// build is here to read and proof what visitors actually see, not to translate from.
// content/i18n.csv (scripts/i18n-export.mjs) is the machine-readable twin — one row
// per string, one column per language — and the file a finished translation comes
// back in. This one is the text grouped the way a person reads it: per site, per
// tour, per screen, with each question's correct answer marked.
// ponytail: vi | en only — the other six have no strings.js block, add one here when they do.
import { readFileSync, writeFileSync } from 'node:fs';

const LANG = process.argv[2] ?? 'vi';
if (LANG !== 'vi' && LANG !== 'en') {
  console.error(`unsupported language "${LANG}" — vi or en`);
  process.exit(1);
}

const DATA = new URL('../src/lib/data/', import.meta.url);
const load = (f) => JSON.parse(readFileSync(new URL(f, DATA), 'utf8'));
const dests = load('destinations.json');
const tours = load('tours.json');
const rewards = load('rewards.json');
const cats = load('categories.json');
const tickets = load('ticket-points.json');

const L = {
  vi: {
    head: '# Tuần lễ Sáng tạo Hội An 2026 — toàn bộ văn bản',
    intro: [
      'Sinh bởi `node scripts/export-full-text.mjs`. Chỉ tiếng Việt — bản gốc để dịch sang các thứ tiếng khác.',
      'Điền bản dịch về `content/i18n.csv` (một dòng một chuỗi, một cột một ngôn ngữ).',
      '',
      'Chuỗi có `{n}` `{name}` `{i}`… là chỗ ứng dụng chèn số/tên vào — dịch xung quanh, giữ nguyên trong ngoặc.'
    ],
    dests: (o, c) => `## 1. Điểm đến — ${o} điểm đang mở (${c} điểm đóng ở cuối mục)`,
    closed: ' — ĐANG ĐÓNG',
    name: 'Tên', addr: 'Địa chỉ', hours: 'Giờ mở cửa',
    short: 'Giới thiệu ngắn', long: 'Giới thiệu dài',
    highlights: 'Đừng bỏ lỡ',
    q: (i) => `Câu hỏi ${i}`, question: 'Câu hỏi',
    right: 'ĐÁP ÁN ĐÚNG', option: 'Đáp án', explain: 'Giải thích',
    tours: (n) => `## 2. Tuyến — ${n}`,
    voucher: 'Quà', stops: 'Chặng',
    rewards: (n) => `## 3. Bậc quà — ${n}`,
    tier: (p, t) => `### ${p} điểm — ${t}`,
    title: 'Tiêu đề', reward: 'Phần quà',
    cats: (n) => `## 4. Nhóm điểm đến — ${n}`,
    tickets: (n) => `## 5. Điểm bán vé — ${n}`,
    ui: (n) => `## 6. Chữ trong ứng dụng — ${n}`,
    greet: '## 7. Lời chào ở màn chọn ngôn ngữ',
    greetNote: 'Đã viết bằng chính ngôn ngữ đó — chỉ soát lại, không dịch.'
  },
  en: {
    head: '# Hội An Creative Week 2026 — all text',
    intro: [
      'Generated by `node scripts/export-full-text.mjs en`. English as it ships — Vietnamese is the source text.',
      'A line still in Vietnamese below has no English written yet (the app falls back to `vi` the same way).',
      '',
      'Strings with `{n}` `{name}` `{i}`… are where the app inserts a number or name — translate around them, keep the braces.'
    ],
    dests: (o, c) => `## 1. Destinations — ${o} open (${c} closed, at the end of the section)`,
    closed: ' — CLOSED',
    name: 'Name', addr: 'Address', hours: 'Opening hours',
    short: 'Short intro', long: 'Long intro',
    highlights: "Don't miss",
    q: (i) => `Question ${i}`, question: 'Question',
    right: 'CORRECT ANSWER', option: 'Answer', explain: 'Explanation',
    tours: (n) => `## 2. Tours — ${n}`,
    voucher: 'Voucher', stops: 'Stops',
    rewards: (n) => `## 3. Reward tiers — ${n}`,
    tier: (p, t) => `### ${p} points — ${t}`,
    title: 'Title', reward: 'Reward',
    cats: (n) => `## 4. Categories — ${n}`,
    tickets: (n) => `## 5. Ticket counters — ${n}`,
    ui: (n) => `## 6. App interface text — ${n}`,
    greet: '## 7. Greetings on the language screen',
    greetNote: 'Written in each language itself — proofread only, do not translate.'
  }
}[LANG];

const out = [];
const w = (s = '') => out.push(s);
let n = 0;
/** one field in LANG, falling back to vi exactly as the app's t() does */
const pair = (label, f, indent = '') => {
  const v = f?.[LANG] ?? f?.vi;
  if (!v) return;
  n++;
  w(`${indent}- **${label}:** ${v}`);
};
const nameOf = (d) => d?.name?.[LANG] ?? d?.name?.vi;

w(L.head);
w('');
L.intro.forEach(w);
w('');

// ---- destinations ----
const open = dests.filter((d) => !d.closed);
w(L.dests(open.length, dests.length - open.length));
for (const d of [...open, ...dests.filter((x) => x.closed)]) {
  w('');
  w(`### ${d.code ?? '?'} ${nameOf(d)}${d.closed ? L.closed : ''}`);
  pair(L.name, d.name);
  pair(L.addr, d.address);
  pair(L.hours, d.hours);
  pair(L.short, d.short);
  pair(L.long, d.description);
  if (d.highlights?.length) {
    w(`- **${L.highlights}**`);
    d.highlights.forEach((h, i) => pair(`${i + 1}`, h, '  '));
  }
  d.quizBank?.forEach((q, i) => {
    w(`- **${L.q(i + 1)}**`);
    pair(L.question, q.question, '  ');
    q.options.forEach((o, j) => pair(j === q.answer ? L.right : L.option, o, '  '));
    if (q.explain) pair(L.explain, q.explain, '  ');
  });
}

// ---- tours ----
w('');
w(L.tours(tours.length));
for (const t of tours) {
  w('');
  w(`### ${t.title[LANG] ?? t.title.vi}`);
  pair(L.name, t.title);
  pair(L.short, t.short);
  pair(L.long, t.description);
  pair(L.voucher, t.voucher);
  w(`- **${L.stops}:** ${t.stops.map((id) => nameOf(dests.find((d) => d.id === id)) ?? id).join(' → ')}`);
}

// ---- rewards, categories, ticket points ----
w('');
w(L.rewards(rewards.length));
for (const r of rewards) {
  w('');
  w(L.tier(r.points, r.title[LANG] ?? r.title.vi));
  pair(L.title, r.title);
  pair(L.reward, r.reward);
}
w('');
w(L.cats(cats.length));
for (const c of cats) pair(c.id, c.label);
w('');
w(L.tickets(tickets.length));
for (const t of tickets) pair(t.id, t.where);

// ---- UI strings ----
const src = readFileSync(new URL('../src/lib/strings.js', import.meta.url), 'utf8');
const block = (lang) => {
  const start = src.indexOf(`\n  ${lang}:`);
  return src.slice(start, src.indexOf('\n  }', start));
};
const plain = (b) => Object.fromEntries(
  [...b.matchAll(/^ {4}([a-zA-Z_0-9]+)\s*:\s*(['"`])((?:\\.|(?!\2).)*)\2\s*,?\s*$/gm)]
    .map((m) => [m[1], m[3].replace(/\\(['"`\\])/g, '$1')])
);
const fns = (b) => Object.fromEntries(
  [...b.matchAll(/^ {4}([a-zA-Z_0-9]+)\s*:\s*\(([^)]*)\)\s*=>\s*`([^`]*)`/gm)]
    .map((m) => [`${m[1]}()`, m[3].replace(/\$\{([^}]+)\}/g, (_, s) => `{${s.trim()}}`)])
);
const vi = { ...plain(block('vi')), ...fns(block('vi')) };
const en = { ...plain(block('en')), ...fns(block('en')) };
w('');
w(L.ui(Object.keys(vi).length));
w('');
for (const k of Object.keys(vi)) pair(k, { vi: vi[k], en: en[k] });

// ---- the language picker's own greetings ----
const langs = readFileSync(new URL('../src/lib/languages.js', import.meta.url), 'utf8');
w('');
w(L.greet);
w('');
w(L.greetNote);
for (const m of langs.matchAll(/\{ code: '(\w+)',[^}]*hello: '([^']*)'[^}]*name: '([^']*)'[^}]*open: '([^']*)'/g)) {
  w(`- **${m[1]}** ${m[3]} — “${m[2]}” · “${m[4]}”`);
}

const file = LANG === 'vi' ? 'full-text.md' : `full-text-${LANG}.md`;
writeFileSync(new URL(`../content/${file}`, import.meta.url), `${out.join('\n')}\n`);
console.log(`content/${file} — ${n} strings`);
